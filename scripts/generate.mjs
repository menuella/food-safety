// `dart format` would otherwise rewrite what we just emitted, so every
// contributor who ran it would make the generated files look stale. Formatting
// here means the committed output IS the formatted output.
//
// Skipped when the Dart SDK is absent — a JS-only contributor should not need
// it installed, and verify.mjs skips the Dart diff in that case for the same
// reason.
//
// --language-version is load-bearing, not decoration. `dart format` picks its
// style from the package's language version in pubspec.yaml, and verify.mjs
// builds into a temp directory that has no pubspec — so without this flag the
// temp build gets the newer "tall" style, the committed file keeps the short
// one, and every verify run reports a stale file that is perfectly in sync.
try {
  execFileSync(
    "dart",
    ["format", "--language-version=3.6", join(OUT, "packages/dart/lib/src")],
    { stdio: "pipe" },
  )
} catch {
  console.log("note: dart not found — .g.dart emitted unformatted")
}

