// ------------------------------- packages/java/**/kotlin/**/Generated*.kt --
// Kotlin gets GENERATED SOURCE, for the same reason Dart does and a different
// one besides. The JVM has no JSON parser in its standard library, so reading
// the JSON at runtime would mean adding a dependency — and "no dependencies"
// is a property of this dataset worth keeping on every registry it reaches.
//
// One file PER LOCALE, not one big file. A JVM method body is capped at 64 KB
// of bytecode, and six locales of ~300 string constants in a single static
// initializer would sail past it — as a compile error that reads like a
// compiler bug rather than a size problem.
